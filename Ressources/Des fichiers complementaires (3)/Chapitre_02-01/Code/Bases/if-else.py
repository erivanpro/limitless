user_input = input("Veuillez saisir un nombre entier :")
n = int(user_input)
if (n % 2) == 0: 
    # si n est divisible par 2, alors c'est un nombre pair
    # le symbole % représente si n est divisible par un autre nombre (reste de la division)
    print(f"{n} est un nombre pair")
else :
    print(f"{n} est un nombre impair")
     # sinon, c'est un nombre impair
print("fin du programme!")    
       
    




